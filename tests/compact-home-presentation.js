const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const home = html.match(/<button\b[^>]*id="directoryHomeBtn"[^>]*>[\s\S]*?<\/button>/g);
assert.equal(home?.length, 1, 'There is one Home control');
assert.match(home[0], /aria-label="חזרה למסך הבית"/);
assert.match(home[0], /title="חזרה למסך הבית"/);
assert.match(home[0], /<span>בית<\/span>/, 'The compact control retains a visible label');
assert.match(home[0], /onclick="returnToHome_\(\)"/);
assert.match(home[0], / hidden>/, 'The control is hidden until results are shown');
assert.match(html, /<div class="directoryListActions">\s*<button[^>]+id="directoryHomeBtn"/, 'Home shares the existing results action row');
assert.doesNotMatch(html, /<div class="controlsCard">\s*<button[^>]+id="directoryHomeBtn"/, 'Home must not add a row before search');
const rules = css.match(/#app \.directoryHomeBtn \{([^}]+)\}/)?.[1];
assert(rules);
assert.match(rules, /min-width:\s*44px/);
assert.match(rules, /min-height:\s*44px/);
assert.match(rules, /margin:\s*0;/);
assert.match(css, /#app \.directoryHomeBtn:focus-visible\s*\{[^}]*outline:\s*3px/);
console.log('Compact Home placement, visible/accessibility labels and 44px target checks passed.');
